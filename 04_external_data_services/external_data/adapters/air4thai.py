@cache
def _ssl_context() -> ssl.SSLContext:
    context = ssl.create_default_context(cafile=certifi.where())
    context.load_verify_locations(cadata=LETS_ENCRYPT_YR_CHAIN)
    return context


class Air4ThaiPm25(Adapter):
    """Latest PM2.5 at every Pollution Control Department station (~170, no key).

    The value is the 24-hour average that PCD uses for the Thai AQI. Missing readings come as -1.
    """

    name = "air4thai"
    attribution = "ข้อมูลคุณภาพอากาศ: กรมควบคุมมลพิษ (Air4Thai)"
    url = "https://air4thai.pcd.go.th/services/getNewAQI_JSON.php"

    async def fetch(self, client: httpx.AsyncClient) -> Any:
        # Own client: the shared one cannot verify Air4Thai's certificate (see LETS_ENCRYPT_YR_CHAIN).
        async with httpx.AsyncClient(verify=_ssl_context(), headers=client.headers, follow_redirects=True) as own:
            response = await own.get(self.url, timeout=self.timeout_seconds)
        response.raise_for_status()
        return response.json()

    def parse(self, raw: Any, fetched_at: datetime) -> list[SourceRecord]:
        records = []
        for station in raw["stations"]:
            last = station.get("AQILast") or {}
            pm25 = last.get("PM25") or {}
            value = to_float(pm25.get("value"))
            if value is None or value < 0:
                continue
            date, time = last.get("date"), last.get("time")
            records.append(
                SourceRecord(
                    source=self.name,
                    variable="pm25_24h",
                    value=value,
                    unit="µg/m³",
                    lat=to_float(station.get("lat")),
                    lon=to_float(station.get("long")),
                    station_id=station.get("stationID"),
                    # Air4Thai times are Thai local time.
                    observed_at=parse_local(f"{date} {time}", "%Y-%m-%d %H:%M") if date and time else None,
                    fetched_at=fetched_at,
                    attribution=self.attribution,
                    extra={
                        "name_th": station.get("nameTH"),
                        "area_th": station.get("areaTH"),
                        "station_type": station.get("stationType"),
                        "aqi": to_float(pm25.get("aqi")),
                    },
                )
            )
        return records
