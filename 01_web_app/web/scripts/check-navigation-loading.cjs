const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  let release;
  const ready=new Promise(resolve=>{release=resolve;});
  await page.route('**/api/v1/map/layers/overview',async route=>{await ready; await route.continue();});
  await page.goto(process.env.THANPHAI_VERIFY_URL||'http://localhost:3000',{waitUntil:'domcontentloaded'});
  await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).waitFor({timeout:5000});
  assert(await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).locator('.rain-cloud').isVisible(),'Rain cloud skeleton visible while loading');
  if(process.env.SCREENSHOT_PREFIX) await page.screenshot({path:process.env.SCREENSHOT_PREFIX+'-loading.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).locator('.rain-cloud-shape').evaluate(el=>getComputedStyle(el).animationName),'none','Reduced motion disables cloud animation');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.getByRole('button',{name:'เปิดหน้าเว็บระหว่างรอ',exact:true}).click();
  assert(await page.locator('[data-category=water]').isEnabled(),'Can enter while request is pending');
  release();
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).waitFor({state:'hidden'});
  for(const width of [1440,375,320]) {
   await page.setViewportSize({width,height:900});
   await page.locator('[data-category=water]').click();
   const mainButton=page.locator('[data-category=water]');
   const submenu=page.locator('.category-flyout[data-open=true]');
   await submenu.waitFor();
   assert.equal(await submenu.locator('button').count(),4);
   assert.equal(await page.locator('.map-panel .hazard-subtabs').count(),0,'Old map tabs removed');
   const mainBounds=await mainButton.boundingBox();
   await page.waitForTimeout(450);
   const flyoutBounds=await submenu.boundingBox();
   assert(flyoutBounds.x>=0&&flyoutBounds.x+flyoutBounds.width<=width,'Flyout stays inside viewport');
   if(width>1050) assert(flyoutBounds.x>mainBounds.x+mainBounds.width,'Flyout appears beside the main category');
   await page.mouse.move(10,10);await page.waitForTimeout(520);
   const mainSize=await mainButton.boundingBox();
   await mainButton.hover();await page.waitForTimeout(520);
   assert((await mainButton.boundingBox()).width>mainSize.width*1.1,'Main navigation keeps summary-card enlargement');
   await submenu.getByRole('button',{name:'คุณภาพน้ำ',exact:true}).click();
   await page.getByRole('heading',{name:'แผนที่สถานีวัดคุณภาพน้ำ',exact:true}).waitFor();
   assert.equal(await page.locator('.category-flyout[data-open=true]').count(),0,'Selecting a subcategory closes the flyout');
   await page.waitForTimeout(450);
   assert.equal(await page.locator('#topics-water').isVisible(),false,'Selected flyout finishes hiding');
   assert.equal(await mainButton.evaluate(el=>el===document.activeElement),true,'Focus returns to the main category');
   await mainButton.click();
   assert.equal(await submenu.getByRole('button',{name:'คุณภาพน้ำ',exact:true}).getAttribute('aria-pressed'),'true');
   await page.mouse.move(10,10);await page.waitForTimeout(520);
   assert((await submenu.locator('button').first().boundingBox()).height<=38,'Flyout buttons are compact');
   if(process.env.SCREENSHOT_PREFIX && width!==320) await page.screenshot({path:process.env.SCREENSHOT_PREFIX+'-nav-'+width+'.png'});
   assert((await page.locator('.map-options button').first().boundingBox()).height<=36,'Map buttons remain compact');
   assert((await page.locator('.map-hint').boundingBox()).height<32,'Map hint remains compact');
   await page.locator('.journey-header-message').click();
   assert.equal(await page.locator('.category-flyout[data-open=true]').count(),0,'Click outside closes flyout');
   await mainButton.click();
   await mainButton.press('Escape');
   assert.equal(await page.locator('.category-flyout[data-open=true]').count(),0,'Escape closes flyout');
   await page.getByRole('link',{name:'ทันภัย หน้าแรก',exact:true}).click();
   await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).waitFor({state:'hidden'});
   assert.equal(await page.locator('[data-category=overview]').getAttribute('aria-pressed'),'true','Logo returns to overview from a subcategory');
   assert.equal(await page.locator('.map-panel > .hazard-subtabs').count(),0);
   await page.locator('.header-snapshot button').nth(1).click();
   await page.getByRole('link',{name:'ทันภัย หน้าแรก',exact:true}).click();
   await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).waitFor({state:'hidden'});
   assert.equal(await page.locator('[data-risk-level]').count(),0,'Logo clears risk filters');
   assert(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1 && document.documentElement.scrollWidth<=innerWidth),'Layout remains bounded');
  }
  await page.locator('.map-supplement > summary').click();
  await page.getByRole('group',{name:'เปิดปิดชั้นข้อมูลภาพรวม',exact:true}).waitFor();
  await page.locator('[data-layer=pm25]').click();
  assert.equal(await page.locator('[data-layer=pm25]').getAttribute('aria-pressed'),'true','Moved layer controls still work');
  assert(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1),'Layer disclosure stays within viewport');
  await page.locator('.map-supplement > summary').click();
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.route('**/api/v1/map/layers/overview',r=>r.fulfill({status:503,json:{detail:'test unavailable'}}));
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('status',{name:'กำลังเตรียมข้อมูลทันภัย',exact:true}).waitFor({state:'hidden'});
  assert(await page.locator('[data-category=water]').isEnabled(),'Initial fetch failure does not trap loading');
  assert.deepEqual(errors,[]);
  console.log('PASS: rain-cloud loading, error release, anchored flyouts, logo reset, hover enlargement, mobile navigation, and viewport bounds.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
