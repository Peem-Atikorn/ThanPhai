const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:900},permissions:['geolocation'],geolocation:{latitude:14.02,longitude:100.73}});
  const page=await context.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const place={code:'TH130303',level:'tambon',name_th:'รังสิต',parents:['ธัญบุรี','ปทุมธานี'],lat:14.02,lon:100.73};
  let searchCalls=0,locateCalls=0;
  await page.route('**/api/v1/areas/search?*',async r=>{searchCalls++;await r.fulfill({json:[place]});});
  await page.route('**/api/v1/areas/locate?*',r=>{locateCalls++;const url=new URL(r.request().url());assert.equal(Number(url.searchParams.get('lat')),14.02);return r.fulfill({json:place});});
  await page.route('**/api/v1/areas/TH130303/hazards',r=>r.fulfill({json:{area:place,assessments:[],official_warnings:[],forecast:[],rivers:[],dams:[],degraded_services:[]}}));
  await page.goto(process.env.THANPHAI_VERIFY_URL||'http://localhost:3000');
  await page.getByRole('button',{name:'พื้นที่ที่คุณอยากรู้',exact:true}).click();
  const input=page.getByRole('combobox',{name:'ค้นหาพื้นที่',exact:true});
  await input.fill('รัง');
  await page.getByRole('option',{name:/รังสิต/}).waitFor();
  assert(searchCalls>0,'Suggestions appear without submitting');
  assert.equal(await input.evaluate(el=>getComputedStyle(el).outlineStyle),'none','No green input outline');
  await input.press('ArrowDown'); await input.press('Enter');
  await page.getByRole('button',{name:/เปลี่ยนพื้นที่.*รังสิต/}).waitFor();
  assert.equal(await page.getByRole('dialog',{name:'ค้นหาพื้นที่',exact:true}).count(),0);
  await page.getByRole('button',{name:'ล้างพื้นที่ที่ค้นหา',exact:true}).click();
  await page.getByRole('button',{name:'พื้นที่ที่คุณอยากรู้',exact:true}).click();
  assert.equal(await input.inputValue(),'');
  await page.getByRole('button',{name:'ตำแหน่งของฉัน',exact:true}).click();
  await page.getByRole('button',{name:/เปลี่ยนพื้นที่.*รังสิต/}).waitFor();
  assert.equal(locateCalls,1,'GPS maps to a place once');
  await page.locator('[data-category=water]').click();
  await page.getByRole('button',{name:'เขื่อน',exact:true}).click();
  assert.match(await page.locator('.location-scope').innerText(),/รังสิต/);
  await page.setViewportSize({width:375,height:667});
  assert(await page.locator('.journey-search-icon.has-location > span').isVisible(),'Selected place visible on mobile');
  assert(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1&&document.documentElement.scrollWidth<=innerWidth));
  if(process.env.SCREENSHOT_PREFIX) await page.screenshot({path:process.env.SCREENSHOT_PREFIX+'-selected.png'});
  await page.getByRole('button',{name:/เปลี่ยนพื้นที่.*รังสิต/}).click();
  await page.evaluate(()=>{navigator.geolocation.getCurrentPosition=(_,error)=>error({code:1});});
  await page.getByRole('button',{name:'ตำแหน่งของฉัน',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'อนุญาต'}).waitFor();
  await input.fill('รัง'); await page.getByRole('option',{name:/รังสิต/}).waitFor();
  if(process.env.SCREENSHOT_PREFIX) await page.screenshot({path:process.env.SCREENSHOT_PREFIX+'-search.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: live suggestions, keyboard selection, neutral focus, header label, clear, mocked GPS, denied permission, retained scope and mobile fit.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
